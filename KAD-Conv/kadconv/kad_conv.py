"""KAD-Conv: Kernel Adaptive Deformable Convolution.

Pure PyTorch. The module and parameter names match the KAD-CNet code, so a KAD-Conv
layer can load weights taken from a KAD-CNet checkpoint.
"""
import math

import torch
import torch.nn as nn
import torch.nn.functional as F
import torchvision

# BatchNorm settings used when training KAD-CNet (YOLO convention); needed to reproduce its weights.
BN_EPS = 1e-3
BN_MOMENTUM = 0.03


class LCSA(nn.Module):
    """Low-Cost Spatial Attention: row/column pooling followed by strip convolutions.

    Produces the (pre-sigmoid) modulation mask of DSC from axial global context.
    """

    def __init__(self, in_channels, out_channels, band_kernel_size=11):
        super().__init__()
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))
        self.excite = nn.Sequential(
            nn.Conv2d(in_channels, in_channels, (1, band_kernel_size),
                      padding=(0, band_kernel_size // 2), groups=in_channels),
            nn.BatchNorm2d(in_channels, eps=BN_EPS, momentum=BN_MOMENTUM),
            nn.ReLU(inplace=True),
            nn.Conv2d(in_channels, in_channels, (band_kernel_size, 1),
                      padding=(band_kernel_size // 2, 0), groups=in_channels),
            nn.Conv2d(in_channels, out_channels, 1),
        )

    def forward(self, x):
        return self.excite(self.pool_h(x) + self.pool_w(x))


class DSC(nn.Module):
    """Deformable Spatial Convolution: modulated 3x3 deformable convolution (DCNv2)
    whose modulation mask is generated by LCSA instead of a local convolution."""

    def __init__(self, in_channels, out_channels, kernel_size=3, stride=1, padding=1):
        super().__init__()
        self.in_channels, self.out_channels = in_channels, out_channels
        self.kernel_size = kernel_size
        self.mask = True  # attribute read by the accelerated forward
        self.stride = (stride, stride)
        self.padding = padding
        self.weight = nn.Parameter(torch.empty(out_channels, in_channels, kernel_size, kernel_size))
        self.bias = nn.Parameter(torch.zeros(out_channels))
        self.conv_offset = nn.Conv2d(in_channels, 2 * kernel_size * kernel_size, kernel_size,
                                     stride=stride, padding=padding)
        self.RCA_mask = LCSA(in_channels, kernel_size * kernel_size)
        stdv = 1.0 / math.sqrt(in_channels * kernel_size * kernel_size)
        nn.init.uniform_(self.weight, -stdv, stdv)
        nn.init.zeros_(self.conv_offset.weight)
        nn.init.zeros_(self.conv_offset.bias)

    def forward(self, x):
        offset = self.conv_offset(x)
        mask = torch.sigmoid(self.RCA_mask(x))
        return torchvision.ops.deform_conv2d(x, offset, self.weight, self.bias,
                                             stride=self.stride, padding=self.padding, mask=mask)


class _Scale(nn.Module):
    """Learnable per-channel branch weight."""

    def __init__(self, dims):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(*dims))

    def forward(self, x):
        return x * self.weight


class KADConv(nn.Module):
    """Kernel Adaptive Deformable Convolution.

    The input is processed by ``n`` branches at relative resolutions 1, 1/2, ..., 1/2^(n-1).
    Each branch is a 1x1 projection followed by DSC; branches are weighted by learnable
    scales (branch selection) and channel attention (channel selection), upsampled back,
    concatenated and added to the input. Input and output have the same shape.

    Args:
        dim: number of input/output channels.
        n: number of branches (3 in the paper).
        se_min_hidden: minimum hidden width of the channel attention. KAD-CNet-S uses 32;
            the MGL-trained KAD-CNet-S checkpoint uses 64.
    """

    def __init__(self, dim, n=3, se_min_hidden=32):
        super().__init__()
        self.n = n
        widths = [dim - (dim // n) * (n - 1)] + [dim // n] * (n - 1)
        self.convs = nn.ModuleList([
            nn.Sequential(nn.Conv2d(dim, c, 1), DSC(c, c),
                          nn.BatchNorm2d(c, eps=BN_EPS, momentum=BN_MOMENTUM), nn.ReLU(inplace=True))
            for c in widths
        ])
        self.fc = nn.ModuleList([
            nn.Sequential(nn.Linear(c, max(se_min_hidden, c)), nn.ReLU(),
                          nn.Linear(max(se_min_hidden, c), c), nn.Sigmoid())
            for c in widths
        ])
        self.weight = nn.ModuleList([nn.Sequential(_Scale([1, c, 1, 1])) for c in widths])

    def forward(self, x):
        features = []
        for i, (conv, fc, w) in enumerate(zip(self.convs, self.fc, self.weight)):
            y = F.avg_pool2d(x, kernel_size=2 ** i) if i > 0 else x
            y = w(conv(y))
            y = y * fc(y.mean(dim=(2, 3))).view(x.size(0), -1, 1, 1)
            if i > 0:
                y = F.interpolate(y, size=x.shape[2:], mode='bilinear', align_corners=False)
            features.append(y)
        return torch.cat(features, dim=1) + x
